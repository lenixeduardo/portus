CREATE TABLE public.lab_templates (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE CHECK (btrim(code) <> '')
);

CREATE TABLE public.lab_parameters (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE CHECK (btrim(code) <> ''),
  name TEXT NOT NULL CHECK (btrim(name) <> '')
);

CREATE TABLE public.lab_template_versions (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES public.lab_templates(id),
  version INTEGER NOT NULL CHECK (version > 0),
  source_document TEXT NOT NULL CHECK (btrim(source_document) <> ''),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved')),
  approved_by BIGINT,
  approved_at TIMESTAMPTZ,
  change_serial BIGINT NOT NULL DEFAULT 0,
  UNIQUE (template_id, version),
  CHECK ((status = 'draft' AND approved_by IS NULL AND approved_at IS NULL)
      OR (status = 'approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);

CREATE TABLE public.lab_template_parameters (
  template_version_id BIGINT NOT NULL REFERENCES public.lab_template_versions(id),
  parameter_id BIGINT NOT NULL REFERENCES public.lab_parameters(id),
  original_name TEXT NOT NULL CHECK (btrim(original_name) <> ''),
  value_type TEXT NOT NULL CHECK (value_type IN ('quantitative', 'qualitative')),
  origin TEXT CHECK (origin IN ('manual', 'instrumental', 'calculated')),
  original_unit TEXT,
  unit TEXT CHECK (btrim(unit) <> ''),
  required BOOLEAN,
  decimal_precision INTEGER CHECK (decimal_precision >= 0),
  method TEXT,
  reference_temperature_c NUMERIC,
  wavelength_nm NUMERIC CHECK (wavelength_nm > 0),
  sample_concentration_percent NUMERIC CHECK (sample_concentration_percent BETWEEN 0 AND 100),
  equipment_id BIGINT REFERENCES public.equipments(id),
  source_evidence TEXT NOT NULL CHECK (btrim(source_evidence) <> ''),
  notes TEXT,
  PRIMARY KEY (template_version_id, parameter_id),
  CHECK (value_type = 'quantitative' OR (unit IS NULL AND decimal_precision IS NULL))
);

CREATE TABLE public.lab_product_specifications (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id),
  template_version_id BIGINT NOT NULL REFERENCES public.lab_template_versions(id),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved')),
  effective_from TIMESTAMPTZ NOT NULL DEFAULT now(),
  effective_until TIMESTAMPTZ,
  approved_by BIGINT,
  approved_at TIMESTAMPTZ,
  change_serial BIGINT NOT NULL DEFAULT 0,
  UNIQUE (id, template_version_id),
  UNIQUE (id, product_id, template_version_id),
  CHECK (effective_until IS NULL OR effective_until > effective_from),
  CHECK ((status = 'draft' AND approved_by IS NULL AND approved_at IS NULL)
      OR (status = 'approved' AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);

CREATE UNIQUE INDEX lab_specification_product_effective_idx
  ON public.lab_product_specifications (product_id, effective_from) WHERE status = 'approved';

CREATE TABLE public.lab_product_specification_clocks (
  product_id BIGINT PRIMARY KEY REFERENCES public.products(id) ON DELETE CASCADE,
  serial BIGINT NOT NULL CHECK (serial > 0)
);

CREATE FUNCTION public.lab_touch_specifications(p_product_id BIGINT)
RETURNS VOID
LANGUAGE sql
SET search_path = pg_catalog, pg_temp
AS $$
  INSERT INTO public.lab_product_specification_clocks AS product_clock (product_id, serial)
  VALUES (p_product_id, 1)
  ON CONFLICT (product_id) DO UPDATE SET serial = product_clock.serial + 1;
$$;

CREATE TABLE public.lab_spec_limits (
  specification_id BIGINT NOT NULL,
  template_version_id BIGINT NOT NULL,
  parameter_id BIGINT NOT NULL,
  value_type TEXT NOT NULL CHECK (value_type IN ('quantitative', 'qualitative')),
  unit TEXT CHECK (btrim(unit) <> ''),
  minimum_value NUMERIC,
  maximum_value NUMERIC,
  minimum_inclusive BOOLEAN NOT NULL DEFAULT TRUE,
  maximum_inclusive BOOLEAN NOT NULL DEFAULT TRUE,
  qualitative_value TEXT CHECK (btrim(qualitative_value) <> ''),
  source_evidence TEXT CHECK (btrim(source_evidence) <> ''),
  PRIMARY KEY (specification_id, parameter_id),
  FOREIGN KEY (specification_id, template_version_id)
    REFERENCES public.lab_product_specifications(id, template_version_id),
  FOREIGN KEY (template_version_id, parameter_id)
    REFERENCES public.lab_template_parameters(template_version_id, parameter_id),
  CHECK (minimum_value NOT IN ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)),
  CHECK (maximum_value NOT IN ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)),
  CHECK (minimum_value IS NULL OR maximum_value IS NULL OR minimum_value < maximum_value
      OR (minimum_value = maximum_value AND minimum_inclusive AND maximum_inclusive)),
  CHECK ((value_type = 'quantitative' AND unit IS NOT NULL AND qualitative_value IS NULL
          AND (minimum_value IS NOT NULL OR maximum_value IS NOT NULL))
      OR (value_type = 'qualitative' AND unit IS NULL AND qualitative_value IS NOT NULL
          AND minimum_value IS NULL AND maximum_value IS NULL))
);

CREATE TABLE public.lab_template_validation_issues (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  template_version_id BIGINT NOT NULL REFERENCES public.lab_template_versions(id),
  code TEXT NOT NULL CHECK (btrim(code) <> ''),
  details TEXT NOT NULL CHECK (btrim(details) <> ''),
  resolution_evidence TEXT CHECK (btrim(resolution_evidence) <> ''),
  UNIQUE (template_version_id, code)
);

-- Increment the parent row when a child changes so approvals also serialize
-- against changes made by a transaction using REPEATABLE READ.
CREATE FUNCTION public.lab_guard_spec_children()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  parent_id BIGINT;
  locked_version_id BIGINT;
  parameter_type TEXT;
  parameter_unit TEXT;
BEGIN
  IF TG_TABLE_NAME = 'lab_spec_limits' THEN
    IF TG_OP = 'UPDATE' AND
      (NEW.specification_id, NEW.template_version_id, NEW.parameter_id)
        IS DISTINCT FROM (OLD.specification_id, OLD.template_version_id, OLD.parameter_id) THEN
      RAISE EXCEPTION 'The specification limit identity cannot change' USING ERRCODE = '23514';
    END IF;
    parent_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.specification_id ELSE NEW.specification_id END;
    UPDATE public.lab_product_specifications SET change_serial = change_serial + 1
      WHERE id = parent_id AND status = 'draft' RETURNING template_version_id INTO locked_version_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Only draft specification limits can change' USING ERRCODE = '23514';
    END IF;

    IF TG_OP <> 'DELETE' THEN
      SELECT value_type, unit INTO parameter_type, parameter_unit
      FROM public.lab_template_parameters
      WHERE template_version_id = locked_version_id AND parameter_id = NEW.parameter_id;
      IF parameter_type IS DISTINCT FROM NEW.value_type OR parameter_unit IS DISTINCT FROM NEW.unit THEN
        RAISE EXCEPTION 'Limit type or unit differs from the template parameter' USING ERRCODE = '23514';
      END IF;
    END IF;
  ELSE
    IF TG_OP = 'UPDATE' AND NEW.template_version_id <> OLD.template_version_id THEN
      RAISE EXCEPTION 'The template version cannot change' USING ERRCODE = '23514';
    END IF;
    parent_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.template_version_id ELSE NEW.template_version_id END;
    UPDATE public.lab_template_versions SET change_serial = change_serial + 1
      WHERE id = parent_id AND status = 'draft';
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Only draft template content can change' USING ERRCODE = '23514';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER lab_template_parameters_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.lab_template_parameters
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_spec_children();
CREATE TRIGGER lab_template_issues_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.lab_template_validation_issues
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_spec_children();
CREATE TRIGGER lab_spec_limits_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.lab_spec_limits
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_spec_children();

CREATE FUNCTION public.lab_guard_spec_approval()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  IF TG_OP <> 'INSERT' AND OLD.status = 'approved' THEN
    RAISE EXCEPTION 'Approved laboratory data is immutable' USING ERRCODE = '23514';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  IF NEW.status = 'draft' THEN RETURN NEW; END IF;
  IF TG_OP = 'INSERT' THEN
    RAISE EXCEPTION 'A laboratory revision must start as draft' USING ERRCODE = '23514';
  END IF;

  PERFORM 1 FROM public.users WHERE id = NEW.approved_by AND active FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'An active user must approve laboratory revisions' USING ERRCODE = '23514';
  END IF;

  IF TG_TABLE_NAME = 'lab_template_versions' THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.lab_template_parameters WHERE template_version_id = NEW.id AND required
    ) OR EXISTS (
      SELECT 1 FROM public.lab_template_parameters
      WHERE template_version_id = NEW.id
        AND (required IS NULL OR origin IS NULL OR (value_type = 'quantitative' AND unit IS NULL))
    ) OR EXISTS (
      SELECT 1 FROM public.lab_template_validation_issues
      WHERE template_version_id = NEW.id AND resolution_evidence IS NULL
    ) THEN
      RAISE EXCEPTION 'Template review is incomplete or has unresolved source issues' USING ERRCODE = '23514';
    END IF;
  ELSE
    PERFORM public.lab_touch_specifications(NEW.product_id);
    IF NOT EXISTS (
      SELECT 1 FROM public.lab_template_versions WHERE id = NEW.template_version_id AND status = 'approved'
    ) OR EXISTS (
      SELECT 1
      FROM public.lab_template_parameters AS parameter
      LEFT JOIN public.lab_spec_limits AS limits
        ON limits.specification_id = NEW.id AND limits.parameter_id = parameter.parameter_id
      WHERE parameter.template_version_id = NEW.template_version_id
        AND ((parameter.required AND limits.parameter_id IS NULL)
             OR (limits.parameter_id IS NOT NULL AND (
               limits.value_type <> parameter.value_type OR limits.unit IS DISTINCT FROM parameter.unit
             )))
    ) THEN
      RAISE EXCEPTION 'Specification review is incomplete or limits conflict with the approved template' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER lab_template_approval_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.lab_template_versions
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_spec_approval();
CREATE TRIGGER lab_specification_approval_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.lab_product_specifications
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_spec_approval();

CREATE FUNCTION public.lab_guard_parameter_identity()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  IF to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) THEN
    RAISE EXCEPTION 'Laboratory parameter and model identities are immutable' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER lab_template_code_guard BEFORE UPDATE ON public.lab_templates
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_parameter_identity();
CREATE TRIGGER lab_parameter_code_guard BEFORE UPDATE ON public.lab_parameters
  FOR EACH ROW EXECUTE FUNCTION public.lab_guard_parameter_identity();

