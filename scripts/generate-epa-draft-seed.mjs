import { readFileSync, writeFileSync } from 'node:fs';

const matrix = (name) => JSON.parse(
  readFileSync(new URL(`../docs/epa-matrix/epa_${name}.json`, import.meta.url), 'utf8'),
);
const migration = new URL('../database/migrations/027_lab_specifications.sql', import.meta.url);
const models = matrix('models');
const specs = matrix('specifications');
const modelCodes = new Set(models.map((model) => model.codigo_modelo));
const key = (row) => JSON.stringify([row.codigo_modelo, row.codigo_parametro]);
const specsByKey = new Map(specs.map((spec) => [key(spec), spec]));
const origins = { calculada: 'calculated', instrumental: 'instrumental', manual: 'manual' };
const parameters = matrix('parameters').map((parameter) => {
  const evidence = specsByKey.get(key(parameter));

  if (!modelCodes.has(parameter.codigo_modelo) || !evidence) {
    throw new Error(`Missing model or specification for ${key(parameter)}`);
  }

  return {
    model: parameter.codigo_modelo,
    code: parameter.codigo_parametro,
    name: parameter.comprimento_onda_nm ? parameter.nome_original : parameter.nome_normalizado,
    original_name: parameter.nome_original,
    value_type: parameter.tipo === 'quantitativo' ? 'quantitative' : 'qualitative',
    origin: origins[parameter.origem] ?? null,
    original_unit: parameter.unidade_original,
    unit: parameter.tipo === 'quantitativo' ? parameter.unidade_normalizada : null,
    required: parameter.obrigatorio,
    decimal_precision: parameter.precisao_decimal,
    method: parameter.metodo,
    reference_temperature_c: parameter.temperatura_referencia_c,
    wavelength_nm: parameter.comprimento_onda_nm,
    sample_concentration_percent: parameter.concentracao_amostra_pct,
    source_evidence: JSON.stringify({
      reference: parameter.evidencia_documental,
      criterion: evidence.especificado_original,
      marker: parameter.marcador_formulario,
      phase: parameter.etapa_explicitada,
      displayed_precision: parameter.casas_decimais_exibidas,
      proposed_formula: parameter.formula_candidata,
    }),
    notes: parameter.observacoes,
  };
});
const issues = matrix('validation_issues').map((issue) => {
  if (!modelCodes.has(issue.codigo_modelo) ||
      (issue.codigo_parametro && !specsByKey.has(key(issue))) ||
      issue.status !== 'aberta') {
    throw new Error(`Invalid draft issue: ${JSON.stringify(issue)}`);
  }

  return {
    model: issue.codigo_modelo,
    code: [issue.codigo_pendencia, issue.codigo_parametro].filter(Boolean).join(':'),
    details: `${issue.observacoes} Fonte: ${issue.evidencia_documental}`,
  };
});
if (modelCodes.size !== 19 || new Set(parameters.map((row) => JSON.stringify([row.model, row.code]))).size !== specsByKey.size ||
    parameters.length !== specs.length) {
  throw new Error('The EPA source matrix has missing or duplicate keys');
}

function jsonb(rows) {
  return `'${JSON.stringify(rows, null, 2).replaceAll("'", "''")}'::jsonb`;
}

const parametersByCode = Array.from(new Map(parameters.map(({ code, name }) => [code, { code, name }])).values());
const block = `-- BEGIN GENERATED EPA DRAFT DATA
-- Generated by scripts/generate-epa-draft-seed.mjs from docs/epa-matrix.
-- Raw evidence only; product assignments, limits, and formula bindings require review.
INSERT INTO public.lab_parameters (code, name)
SELECT source.code, source.name
FROM jsonb_to_recordset(${jsonb(parametersByCode)}) AS source(code TEXT, name TEXT);

INSERT INTO public.lab_template_parameters (
  template_version_id, parameter_id, original_name, value_type, origin, original_unit, unit,
  required, decimal_precision, method, reference_temperature_c, wavelength_nm,
  sample_concentration_percent, source_evidence, notes
)
SELECT version.id, parameter.id, source.original_name, source.value_type, source.origin,
       source.original_unit, source.unit, source.required, source.decimal_precision, source.method,
       source.reference_temperature_c, source.wavelength_nm, source.sample_concentration_percent,
       source.source_evidence, source.notes
FROM jsonb_to_recordset(${jsonb(parameters)}) AS source(
  model TEXT, code TEXT, original_name TEXT, value_type TEXT, origin TEXT, original_unit TEXT,
  unit TEXT, required BOOLEAN, decimal_precision INT, method TEXT, reference_temperature_c NUMERIC,
  wavelength_nm NUMERIC, sample_concentration_percent NUMERIC, source_evidence TEXT, notes TEXT
)
JOIN public.lab_templates AS template ON template.code = source.model
JOIN public.lab_template_versions AS version ON version.template_id = template.id AND version.version = 1
JOIN public.lab_parameters AS parameter ON parameter.code = source.code;

INSERT INTO public.lab_template_validation_issues (template_version_id, code, details)
SELECT version.id, source.code, source.details
FROM jsonb_to_recordset(${jsonb(issues)}) AS source(model TEXT, code TEXT, details TEXT)
JOIN public.lab_templates AS template ON template.code = source.model
JOIN public.lab_template_versions AS version ON version.template_id = template.id AND version.version = 1;
-- END GENERATED EPA DRAFT DATA`;

const contents = readFileSync(migration, 'utf8');
const existingBlock = /-- BEGIN GENERATED EPA DRAFT DATA[\s\S]*?-- END GENERATED EPA DRAFT DATA/;
const updated = contents.replace(existingBlock, () => block);
if (!existingBlock.test(contents)) {
  throw new Error('Missing generated block markers in migration 027');
}
if (process.argv.includes('--write')) {
  writeFileSync(migration, updated);
} else if (contents !== updated) {
  throw new Error('Migration 027 differs from the EPA source matrix. Run with --write.');
}
